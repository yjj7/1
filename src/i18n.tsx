const LangCtx = createContext<{ lang: Lang; t: (k: string) => string; setLang: (l: Lang) => void }>({ lang: 'zh', t: (k) => k, setLang: () => {} });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem('swm_lang') as Lang) || 'zh');
  const t = useCallback((key: string) => translations[lang]?.[key] || key, [lang]);
  const handleSetLang = (l: Lang) => { setLang(l); localStorage.setItem('swm_lang', l); };
  return <LangCtx.Provider value={{ lang, t, setLang: handleSetLang }}>{children}</LangCtx.Provider>;
}

export function useT() { return useContext(LangCtx); }
export function getTranslations(lang: Lang) { return translations[lang]; }